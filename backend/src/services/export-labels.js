// t(key, vars): the label in the language, {name} placeholders filled; the key itself when it is unknown.
export function labels(lang) {
  const dict = lang === 'en' ? en : ar;
  const t = (key, vars = {}) => (Object.hasOwn(dict, key) ? dict[key] : key).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  // name of a row in the language: name_en / name_ar (or another base such as 'app_name', 'role_name')
  const nm = (o, base = 'name') => (o ? (lang === 'en' && o[base + '_en']) || o[base + '_ar'] || o[base + '_en'] || '' : '');
  return { t, nm, lang };
}
