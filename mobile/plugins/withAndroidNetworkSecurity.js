// Expo config plugin: Android network security configuration of the ETS app (applied by `expo prebuild`).
//
// The ETS server is internal and often uses a certificate from the organisation's own CA, or a self-signed one.
// Release builds trust the system CAs plus the CAs the user installed on the phone (Settings → Security →
// Encryption & credentials → Install a certificate → CA certificate), and never allow plain HTTP.
// Debug builds additionally allow plain HTTP to the Metro development server on this computer only (localhost via
// `adb reverse`, and the emulator's 10.0.2.2), never to any other host.
// Certificate pinning is a later phase (mobile/README.md, phase 3).
const fs = require('node:fs');
const path = require('node:path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const FILE = 'network_security_config';

const TRUST = `        <trust-anchors>
            <certificates src="system" />
            <certificates src="user" />
        </trust-anchors>`;

const releaseXml = () => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidNetworkSecurity.js. No cleartext; system and user-installed CAs. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
${TRUST}
    </base-config>
</network-security-config>
`;

// Hosts of the Metro development server (debug builds only).
const DEV_HOSTS = ['localhost', '127.0.0.1', '10.0.2.2', '10.0.3.2'];
const debugXml = () => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidNetworkSecurity.js (debug builds only): as release, plus plain HTTP to the
     Metro development server on this computer. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
${TRUST}
    </base-config>
    <domain-config cleartextTrafficPermitted="true">
${DEV_HOSTS.map(h => `        <domain includeSubdomains="false">${h}</domain>`).join('\n')}
    </domain-config>
</network-security-config>
`;

// <application android:networkSecurityConfig="@xml/network_security_config">, without usesCleartextTraffic="true".
function applyManifest(manifest) {
  const app = manifest.manifest.application?.[0];
  if (!app) throw new Error('withAndroidNetworkSecurity: AndroidManifest.xml has no <application>');
  app.$['android:networkSecurityConfig'] = `@xml/${FILE}`;
  if (app.$['android:usesCleartextTraffic'] === 'true') delete app.$['android:usesCleartextTraffic'];
  return manifest;
}

function writeXml(androidRoot) {
  for (const [variant, xml] of [['main', releaseXml()], ['debug', debugXml()]]) {
    const dir = path.join(androidRoot, 'app', 'src', variant, 'res', 'xml');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, `${FILE}.xml`), xml);
  }
}

const withAndroidNetworkSecurity = config => {
  config = withAndroidManifest(config, c => { c.modResults = applyManifest(c.modResults); return c; });
  return withDangerousMod(config, ['android', async c => { writeXml(c.modRequest.platformProjectRoot); return c; }]);
};

module.exports = withAndroidNetworkSecurity;
module.exports.releaseXml = releaseXml;
module.exports.debugXml = debugXml;
module.exports.applyManifest = applyManifest;
module.exports.DEV_HOSTS = DEV_HOSTS;
